"""What Den Hurtige plugs into other domains. Imported once, from DenHurtigeConfig.ready().

Today that is a notification category per room, so muting a noisy room is a toggle on the
notifications settings page. Registered from here rather than generated by the notifications app:
notifications is platform, which every feature calls and which may import none of them (tach.toml
layers). It used to import channels.py to build these.
"""

from notifications.api import Category, register_categories

from . import channels

register_categories(
    Category(
        channels.notification_category(channel.slug),
        channel.name,
        group="chat",
        description=f"Nye beskeder i {channel.name}.",
        # Push only: the chat itself is the in-app copy (see notifications.categories).
        in_app=False,
        # The room's bell on the feed links here (den_hurtige/feed.html).
        anchor=f"rum-{channel.slug}",
    )
    for channel in channels.CHANNELS
)
